import 'grammar.dart';
import 'grammar_text.dart';

/// Орус тилинин грамматика плагини.
///
/// AI орусча жазганда көп кетирген каталарды табат:
///  1. Так оңдоолор: кирилл сөздүн ичиндеги латын тамгалары, башка
///     тилдердин тамгалары (қ, ә, і), ашыкча боштуктар, тырмакча «»,
///     «из за» → «из-за» сыяктуу кош жазылуучу сөздөр.
///  2. Шектүү жерлер: -тся/-ться, «в течении/в течение», «так же/также»,
///     орус тексттин ичиндеги кыргызча же англисче сөздөр.
///  3. AI редакторго академиялык орус тилинин эрежелери берилет.
class RussianGrammar extends LanguageGrammar {
  const RussianGrammar();

  @override
  String get name => 'Орус';

  // ------------------------------------------------- 1) автоматтык оңдоо
  /// Орус алфавитинде жок, бирок модель кошуп жиберген тамгалар.
  /// Эскертүү: ө, ү, ң бул жерде ЖОК — алар кыргызча сөздүн белгиси,
  /// аларды тамга катары алмаштырбай, өзүнчө шектүү жер катары көрсөтөбүз.
  static const Map<String, String> _foreignLetters = {
    'қ': 'к', 'Қ': 'К',
    'ғ': 'г', 'Ғ': 'Г',
    'ұ': 'у', 'Ұ': 'У',
    'і': 'и', 'І': 'И',
    'ә': 'э', 'Ә': 'Э',
    'һ': 'х', 'Һ': 'Х',
    'ҳ': 'х', 'Ҳ': 'Х',
    'ҷ': 'ч', 'Ҷ': 'Ч',
    'ӣ': 'и', 'ӯ': 'у',
    'ҙ': 'з', 'ҫ': 'с',
  };

  /// Бөлөк жазылып кеткен сөздөр → туурасы.
  static const Map<String, String> _joined = {
    'из за': 'из-за',
    'из под': 'из-под',
    'по этому': 'поэтому',
    'по тому': 'потому',
    'в начале': 'вначале',
    'не смотря на': 'несмотря на',
    'в последствии': 'впоследствии',
    'в заключении': 'в заключение',
  };

  /// Сөздүн чеги. Dart'тын \b белгиси латын тамгалары боюнча гана иштейт,
  /// ошондуктан кириллица үчүн өзүбүз жазабыз.
  static const String _wb = r'(?<![А-Яа-яЁёA-Za-z0-9_-])';
  static const String _we = r'(?![А-Яа-яЁёA-Za-z0-9_-])';

  static RegExp _phrase(String words) => RegExp(
        '$_wb${words.replaceAll(' ', r'\s+')}$_we',
        caseSensitive: false,
        unicode: true,
      );

  @override
  (String, int) autoFix(String text) {
    var n = 0;

    // Бөтөн тамгалар
    final b = StringBuffer();
    for (final r in text.runes) {
      final ch = String.fromCharCode(r);
      final rep = _foreignLetters[ch];
      if (rep != null) {
        b.write(rep);
        n++;
      } else {
        b.write(ch);
      }
    }
    var s = b.toString();

    // Кирилл сөздүн ичиндеги латын тамгалары
    final mixed = GrammarText.fixMixedLetters(s);
    s = mixed.$1;
    n += mixed.$2;

    // «из за» → «из-за» (сөздүн чеги менен, регистрди сактап)
    for (final e in _joined.entries) {
      s = s.replaceAllMapped(_phrase(e.key), (m) {
        // «в начале» туура да болушу мүмкүн («в начале главы») — аны
        // автоматтык оңдобойбуз, шектүү жер катары гана көрсөтөбүз.
        if (e.key == 'в начале' || e.key == 'в заключении') return m.group(0)!;
        n++;
        final fixed = e.value;
        final first = m.group(0)![0];
        return first == first.toUpperCase()
            ? '${fixed[0].toUpperCase()}${fixed.substring(1)}'
            : fixed;
      });
    }

    final sp = GrammarText.fixSpacing(s);
    s = sp.$1;
    n += sp.$2;

    final q = GrammarText.fixQuotes(s);
    s = q.$1;
    n += q.$2;

    // Сөздөрдүн ортосундагы дефис — сызыкчага (орус типографиясы).
    s = s.replaceAllMapped(
        RegExp(r'([а-яёА-ЯЁ]) - (?=[а-яёА-ЯЁ])', unicode: true), (m) {
      n++;
      return '${m.group(1)} — ';
    });

    return (s, n);
  }

  // --------------------------------------------- 2) шектүү жерлерди табуу
  /// Ушул сөздөрдөн кийинки этиш «-ться» болот (эмне кылуу?).
  static const Set<String> _needInfinitive = {
    'может', 'могут', 'можно', 'нужно', 'надо', 'должен', 'должна',
    'должно', 'должны', 'следует', 'необходимо', 'стоит', 'будет',
    'будут', 'начинает', 'начинают', 'продолжает', 'продолжают',
    'позволяет', 'позволяют', 'требуется', 'предстоит',
  };

  /// Орус тексттинде болбошу керек болгон сөздөр.
  static const Map<String, String> _foreignWords = {
    'жана': 'и',
    'менен': 'с / посредством',
    'үчүн': 'для',
    'болуп': 'являясь',
    'the': 'артикль — в русском тексте не нужен',
    'and': 'и',
    'is': 'есть / является',
  };

  static final RegExp _wordRe = RegExp(r'[A-Za-zЀ-ԯ]+', unicode: true);

  @override
  List<String> findIssues(String text) {
    final out = <String>{};
    final words = _wordRe.allMatches(text).toList();

    for (var i = 0; i < words.length; i++) {
      final orig = words[i].group(0)!;
      final w = orig.toLowerCase();

      // Кыргызча тамгалар — демек кыргызча сөз калып калган
      if (w.contains('ө') || w.contains('ү') || w.contains('ң')) {
        out.add('«$orig» — кыргызча сөз; орусчага которуу керек');
        continue;
      }

      final foreign = _foreignWords[w];
      if (foreign != null) {
        out.add('«$orig» — чет сөз орус тексттинде; орусчасы: $foreign');
        continue;
      }

      // -тся / -ться. Туура форманы өзүбүз жазбайбыз (уңгусу татаал,
      // «окисляется» → «окисляться» сыяктуу) — AI редакторго көрсөтөбүз.
      if (w.endsWith('ться') && w.length > 6) {
        final prev = i > 0 ? words[i - 1].group(0)!.toLowerCase() : '';
        if (prev.isNotEmpty &&
            !_needInfinitive.contains(prev) &&
            !_prepositionLike.contains(prev)) {
          out.add('«$prev $orig» — проверь: «что делает?» → без мягкого '
              'знака (-тся)');
        }
      } else if (w.endsWith('тся') && w.length > 5) {
        final prev = i > 0 ? words[i - 1].group(0)!.toLowerCase() : '';
        if (_needInfinitive.contains(prev)) {
          out.add('«$prev $orig» — после «$prev» нужен инфинитив: '
              '«что делать?» → с мягким знаком (-ться)');
        }
      }
    }

    // Айкаштар
    const phrases = <String, String>{
      'в течении': '«в течении» → «в течение» (убакыт жөнүндө болсо)',
      'в начале': '«в начале» — убакытты билдирсе «вначале» болот, текшер',
      'в заключении':
          '«в заключении» → «в заключение» (корутунду катары болсо)',
      'так же': '«так же» — «тоже/также» маанисинде болсо «также» болот',
      'что бы': '«что бы» — максатты билдирсе «чтобы» болот, текшер',
      'не смотря': '«не смотря» → «несмотря» (карабастан маанисинде)',
    };
    for (final e in phrases.entries) {
      if (_phrase(e.key).hasMatch(text)) out.add(e.value);
    }

    return out.take(40).toList();
  }

  static const Set<String> _prepositionLike = {
    'не', 'бы', 'должны', 'может', 'будет', 'чтобы', 'и', 'или',
  };

  // ------------------------------------------------------ 3) AI редактор
  @override
  String get rules => '''
ПРАВИЛА РУССКОГО ЯЗЫКА (строго соблюдай):
1. Алфавит: только русская кириллица. Буквы ө, ү, ң, қ, ә, і НЕ допускаются.
   Латинские буквы внутри русских слов (c, o, a, p, e) — ошибка.
2. Согласование: род, число и падеж существительного, прилагательного и
   глагола должны совпадать («полученные данные показывают», а не
   «полученные данные показывает»).
3. Управление предлогов: согласно + дательный (согласно расчёту),
   благодаря + дательный, вопреки + дательный, в течение + родительный
   (в течение года), по окончании, при помощи + родительный.
4. -ТСЯ / -ТЬСЯ: «что делает?» — без мягкого знака (вещество окисляется);
   «что делать?» — с мягким знаком (может окисляться).
5. Слитно/раздельно/через дефис: из-за, из-под, поэтому, потому что,
   несмотря на, впоследствии, в течение (времени), чтобы (цель),
   также (= тоже) / так же (= таким же образом).
6. Запятые: перед «который», «что», «чтобы», «если», «так как», «поэтому»
   в сложном предложении; вводные слова (однако, следовательно, таким
   образом, например) выделяются запятыми.
7. Числа и единицы: 3,6 (десятичная запятая), 10 м, 25 °C, 5 мг/л;
   диапазон через тире: 2018–2024 гг.
8. Научный стиль: безличные и страдательные конструкции (рассматривается,
   было установлено), без разговорных слов и без «мы видим, что».
9. Тире между словами — длинное (—), а не дефис (-). Кавычки — «ёлочки».
10. Не повторяй одно и то же слово или мысль подряд.''';

  @override
  String get system => 'Ты грамотный учёный, пишущий академическим русским '
      'языком. Строго соблюдай грамматику русского языка.\n$rules';

  @override
  String proofreadPrompt(String masked, List<String> hints) {
    final h = hints.isEmpty
        ? ''
        : '\nАвтоматическая проверка нашла подозрительные места (проверь '
            'каждое: если верно — оставь, если ошибка — исправь):\n'
            '${hints.map((e) => '- $e').join('\n')}\n';
    return '''
Ты опытный редактор-корректор русского языка. Ниже — раздел самостоятельной
работы студента. Прочитай его целиком, слово за словом, и исправь
грамматику, орфографию и пунктуацию РУССКОГО ЯЗЫКА.

$rules
$h
СТРОГИЕ ТРЕБОВАНИЯ:
- Не меняй содержание, факты и числа, ничего не сокращай и не добавляй.
- Метки вида ⟦0⟧, ⟦1⟧ — это формулы; оставь их КАК ЕСТЬ, на тех же местах.
- Сохрани структуру markdown: строки, списки (-, 1.), символы | в таблицах,
  **жирный** текст.
- Не пиши пояснений, предисловий и фраз вроде «Вот исправленный текст».
- В ответе дай ТОЛЬКО сам исправленный текст.

ТЕКСТ:
<<<
$masked
>>>''';
  }
}
