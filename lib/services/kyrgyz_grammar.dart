/// Кыргыз грамматика плагини.
///
/// AI (Groq) кыргызча жазганда көп кетирген каталарды табат жана оңдойт:
///  1. Жергиликтүү эрежелер (интернетсиз, так): казак/өзбек тамгаларын
///     кыргызчага алмаштыруу, кирилл сөздүн ичиндеги латын тамгаларын
///     оңдоо, ашыкча боштуктар, тыныш белгилер, тырмакча «».
///  2. Шектүү жерлерди табуу: үндүүлөрдүн үндөшүүсү (сингармонизм) бузулган
///     мүчөлөр (-лар/-лер/-лор/-лөр, -нын/-нин/-нун/-нүн ж.б.), кыргыз
///     текстинин ичиндеги орусча сөздөр (и, в, на, что, для ...).
///  3. AI редакторго берилүүчү катуу эрежелер (промпт): ал текстти сөзмө-сөз
///     окуп, грамматиканы оңдойт, мазмунду өзгөртпөйт.
///
/// Формулалар ($...$, $$...$$) жана сүрөт/схема JSON блоктору (```...```)
/// текшерүүдөн мурда ⟦0⟧, ⟦1⟧ ... белгилери менен корголот, кийин кайра
/// ордуна коюлат — ошондуктан алар эч качан бузулбайт.
class KyrgyzGrammar {
  // ------------------------------------------------------------ коргоо
  static final RegExp _protectRe = RegExp(
    r'```[\s\S]*?```|\$\$[\s\S]*?\$\$|\$[^$\n]+\$',
  );

  /// Формула жана код блокторун белгилер менен алмаштырат.
  static (String, List<String>) protect(String text) {
    final saved = <String>[];
    final masked = text.replaceAllMapped(_protectRe, (m) {
      saved.add(m.group(0)!);
      return '⟦${saved.length - 1}⟧';
    });
    return (masked, saved);
  }

  /// Белгилерди кайра ордуна коёт. Бир белги жоголсо же кайталанса — null.
  static String? restore(String masked, List<String> saved) {
    for (var i = 0; i < saved.length; i++) {
      if ('⟦$i⟧'.allMatches(masked).length != 1) return null;
    }
    var out = masked;
    for (var i = 0; i < saved.length; i++) {
      out = out.replaceFirst('⟦$i⟧', saved[i]);
    }
    return out;
  }

  // ------------------------------------------------- 1) автоматтык оңдоо
  /// Кыргыз алфавитинде жок, бирок AI кошуп жиберген тамгалар.
  static const Map<String, String> _foreignLetters = {
    'қ': 'к', 'Қ': 'К', // казак
    'ғ': 'г', 'Ғ': 'Г',
    'ұ': 'у', 'Ұ': 'У',
    'і': 'и', 'І': 'И',
    'ә': 'э', 'Ә': 'Э',
    'һ': 'х', 'Һ': 'Х',
    'ҳ': 'х', 'Ҳ': 'Х', // өзбек/тажик
    'ҷ': 'ч', 'Ҷ': 'Ч',
    'ӣ': 'и', 'ӯ': 'у',
    'ҙ': 'з', 'ҫ': 'с', // башкыр
    'ӧ': 'ө', 'Ӧ': 'Ө', // алтай
    'ӱ': 'ү', 'Ӱ': 'Ү',
    'ҥ': 'ң', 'Ҥ': 'Ң',
    'ҩ': 'ө', // абхаз ө'гө окшош
  };

  /// Кирилл сөздүн ичине кирип калган латын тамгалары (сырты бирдей).
  static const Map<String, String> _latinLook = {
    'a': 'а', 'e': 'е', 'o': 'о', 'p': 'р', 'c': 'с', 'x': 'х', 'y': 'у',
    'A': 'А', 'B': 'В', 'E': 'Е', 'K': 'К', 'M': 'М', 'H': 'Н', 'O': 'О',
    'P': 'Р', 'C': 'С', 'T': 'Т', 'X': 'Х',
  };

  static bool _isCyr(int c) =>
      (c >= 0x0400 && c <= 0x04FF) || (c >= 0x0500 && c <= 0x052F);

  static final RegExp _wordRe = RegExp(r'[A-Za-zЀ-ԯ]+');

  /// Так эрежелер менен оңдойт. Кайтарат: (текст, оңдоолордун саны).
  static (String, int) autoFix(String text) {
    var n = 0;
    final b = StringBuffer();
    for (final r in text.runes) {
      final ch = String.fromCharCode(r);
      final rep = _foreignLetters[ch];
      if (rep != null) {
        b.write(rep);
        n++;
      } else {
        b.write(ch);
      }
    }
    var s = b.toString();

    // Кирилл сөздүн ичиндеги латын тамгалары
    s = s.replaceAllMapped(_wordRe, (m) {
      final w = m.group(0)!;
      final hasCyr = w.codeUnits.any(_isCyr);
      final hasLat = w.codeUnits.any((c) => c < 128);
      if (!hasCyr || !hasLat) return w;
      final o = StringBuffer();
      for (final c in w.split('')) {
        final rep = _latinLook[c];
        if (rep != null) {
          o.write(rep);
          n++;
        } else {
          o.write(c);
        }
      }
      return o.toString();
    });

    // Ашыкча боштуктар (саптын башындагы боштуктарга тийбейбиз)
    s = s.replaceAllMapped(RegExp(r'(\S) {2,}(?=\S)'), (m) {
      n++;
      return '${m.group(1)} ';
    });
    // Тыныш белгинин алдындагы боштук: «сөз ,» -> «сөз,»
    s = s.replaceAllMapped(RegExp(r'(\S) +([,.;:!?])(?=\s|$)'), (m) {
      n++;
      return '${m.group(1)}${m.group(2)}';
    });
    // Кыргызча тексттеги "..." -> «...»
    s = s.replaceAllMapped(RegExp(r'"([^"\n]{1,120})"'), (m) {
      final inner = m.group(1)!;
      if (!inner.codeUnits.any(_isCyr)) return m.group(0)!;
      n++;
      return '«$inner»';
    });
    return (s, n);
  }

  // --------------------------------------------- 2) шектүү жерлерди табуу
  /// Уңгунун акыркы үндүүсү (жок болсо null).
  static String? _lastVowel(String stem) {
    for (var i = stem.length - 1; i >= 0; i--) {
      if ('аыяоуюёеэиөү'.contains(stem[i])) return stem[i];
    }
    return null;
  }

  /// Ачык үндүүлүү мүчө (-лар, -га, -да): у'дан кийин «а» болот
  /// (окуучулар), о'дон кийин «о» (колдор), ү/ө'дөн кийин «ө» (күндөр).
  static String _lowVowel(String v) {
    switch (v) {
      case 'о':
      case 'ё':
        return 'о';
      case 'е':
      case 'э':
      case 'и':
        return 'е';
      case 'ө':
      case 'ү':
        return 'ө';
      default: // а, ы, у, я, ю
        return 'а';
    }
  }

  /// Кууш үндүүлүү мүчө (-нын, -ны, -дык): а/ы → ы, о/у → у, е/и → и, ө/ү → ү.
  static String _highVowel(String v) {
    switch (v) {
      case 'о':
      case 'у':
      case 'ё':
      case 'ю':
        return 'у';
      case 'е':
      case 'э':
      case 'и':
        return 'и';
      case 'ө':
      case 'ү':
        return 'ү';
      default: // а, ы, я
        return 'ы';
    }
  }

  /// Мүчө сыяктуу көрүнгөн, бирок сөздүн өзүнүн бөлүгү болгон учтар
  /// (орусча сөздөр: сектор, транзистор, коридор ...).
  static const _skipEndings = {'тор', 'дор'};

  /// Кыргыз текстинде болбошу керек болгон орусча кызматчы сөздөр.
  static const Map<String, String> _russianWords = {
    'и': 'жана',
    'в': '-да/-де (жатыш жөндөмө)',
    'на': '-га/-да (мүчө менен)',
    'что': 'деген / экенин',
    'это': 'бул',
    'также': 'ошондой эле',
    'который': '-ган/-ген (атоочтук)',
    'которая': '-ган/-ген (атоочтук)',
    'которые': '-ган/-ген (атоочтук)',
    'или': 'же',
    'но': 'бирок',
    'для': 'үчүн',
    'при': '-да (учурунда)',
    'как': 'катары / сыяктуу',
    'если': 'эгерде',
    'то есть': 'башкача айтканда',
  };

  /// Шектүү жерлердин тизмеси (AI редакторго кеңеш катары берилет).
  static List<String> findIssues(String text) {
    final out = <String>{};
    for (final m in _wordRe.allMatches(text)) {
      final orig = m.group(0)!;
      final w = orig.toLowerCase();
      if (!w.codeUnits.every(_isCyr)) continue;

      final ru = _russianWords[w];
      if (ru != null) {
        out.add('«$orig» — орусча сөз; кыргызчасы: $ru');
        continue;
      }
      if (w.length < 6) continue;
      final end = w.substring(w.length - 3);
      final stem = w.substring(0, w.length - 3);
      if (stem.length < 3) continue;
      final v = _lastVowel(stem);
      if (v == null) continue;

      // Көптүк мүчө: -лар/-дар/-тар (жана варианттары)
      if ('лдт'.contains(end[0]) &&
          end[2] == 'р' &&
          'аоеө'.contains(end[1]) &&
          !_skipEndings.contains(end)) {
        final want = _lowVowel(v);
        if (end[1] != want) {
          final fix = '$stem${end[0]}${want}р';
          out.add('«$orig» → «$fix» болушу мүмкүн (үндүүлөрдүн үндөшүүсү)');
        }
        continue;
      }
      // Илик жөндөмө: -нын/-дын/-тын (жана варианттары)
      if ('ндт'.contains(end[0]) && end[2] == 'н' && 'ыуиү'.contains(end[1])) {
        final want = _highVowel(v);
        if (end[1] != want) {
          final fix = '$stem${end[0]}${want}н';
          out.add('«$orig» → «$fix» болушу мүмкүн (үндүүлөрдүн үндөшүүсү)');
        }
      }
    }
    return out.take(40).toList();
  }

  // ------------------------------------------------- 3) AI редактор
  /// Кыргыз тилинин негизги эрежелери (генерацияда да, текшерүүдө да).
  static const String rules = '''
КЫРГЫЗ ТИЛИНИН ЭРЕЖЕЛЕРИ (катуу сакта):
1. Алфавит: кыргыз кирилл алфавити гана (а б в г д е ё ж з и й к л м н ң о ө п р с т у ү ф х ц ч ш щ ъ ы ь э ю я). Казак/өзбек тамгалары (қ, ғ, ә, і, ұ, һ) ЖОК. Ө, Ү, Ң тамгаларын туура жаз: «үчүн», «бөлүм», «өзгөчө», «маани», «мүнөздөмө», «күч», «түрү», «өлчөм», «маңыз».
2. Үндүүлөрдүн үндөшүүсү (сингармонизм): мүчөнүн үндүүсү уңгунун акыркы үндүүсүнө жараша болот.
   Ачык үндүүлүү мүчөлөр (-лар, -га, -да, -дан): а, ы, у → а (адамдар, окуучулар, окуучуга); о → о (колдор, тоого); е, и → е (китептер, мектепке); ө, ү → ө (көлдөр, күндөр, үйдө).
   Кууш үндүүлүү мүчөлөр (-нын, -ны, -дык): а, ы → ы (адамдын); о, у → у (токтун, окуучунун); е, и → и (мектептин); ө, ү → ү (күчтүн, көлдүн).
3. Үнсүздөрдүн ассимиляциясы: каткалаң үнсүздөн (к, п, с, т, ф, х, ц, ч, ш) кийин мүчө каткалаң башталат: -тар, -тын, -ка, -та, -тан (мисалы: эсептер, бөлүктүн, ысык+ка → ысыкка, иште). Үндүүдөн кийин илик -нын, табыш -ны (маселенин, энергияны).
4. Сөз тартиби: ээ — толуктооч — баяндооч; этиш сүйлөмдүн аягында турат. Орус тилинен сөзмө-сөз которулган түзүлүштөрдөн кач.
5. Орусча кызматчы сөздөрдү колдонбо: и → жана, но → бирок, или → же, для → үчүн, также → ошондой эле, который → -ган/-ген атоочтук.
6. Илимий терминдер: кыргызча калыптанган термин болсо ошону колдон (ток күчү, чыңалуу, каршылык, кубаттуулук, ылдамдык, ылдамдануу, тартылуу күчү). Кыргызчасы жок эл аралык терминдер орусча жазылышында калат (энергия, физика, транзистор, интеграл).
7. Ордуна коюлган сан атооч: «1-бөлүм», «3-сүрөт», «XX кылым».
8. Тыныш белгилер: «бирок», «анткени», «ошондуктан» алдынан үтүр; тырмакча «...».
9. Стиль: академиялык, так жана түшүнүктүү; бир эле сөздү кайталаба.''';

  /// Бир бөлүмдү текшерүү үчүн промпт.
  static String proofreadPrompt(String masked, List<String> hints) {
    final h = hints.isEmpty
        ? ''
        : '\nАвтоматтык текшерүү төмөнкү шектүү жерлерди тапты (ар бирин '
            'текшер; туура болсо калтыр, ката болсо оңдо):\n'
            '${hints.map((e) => '- $e').join('\n')}\n';
    return '''
Сен кыргыз тилинин тажрыйбалуу редакторусуң (корректор). Төмөндөгү текст
студенттин СРС ишинин бир бөлүмү. Аны башынан аягына чейин ар бир сөзүн
шашылбай окуп чык жана КЫРГЫЗ ТИЛИНИН грамматикасын, орфографиясын жана
тыныш белгилерин оңдо.

$rules
$h
КАТУУ ТАЛАПТАР:
- Мазмунду, фактыларды, сандарды өзгөртпө, кыскартпа жана жаңы маалымат кошпо.
- ⟦0⟧, ⟦1⟧ сыяктуу белгилер — формулалар; аларды ОШОЛ БОЙДОН, ошол эле орунда калтыр.
- Markdown түзүлүшүн сакта: саптар, тизмелер (-, 1.), таблицанын | сызыктары, **калың** белгилер.
- Түшүндүрмө, баш сөз, «Мына оңдолгон текст» сыяктуу сөздөрдү ЖАЗБА.
- Жоопко ОҢДОЛГОН ТЕКСТТИН ӨЗҮН ГАНА бер.

ТЕКСТ:
<<<
$masked
>>>''';
  }

  /// AI жообунан ашыкча нерселерди тазалайт.
  static String cleanResponse(String r) {
    var s = r.trim();
    s = s.replaceAll('<<<', '').replaceAll('>>>', '').trim();
    // Бүт жооп ``` ичине оролгон болсо
    final fence = RegExp(r'^```[a-zA-Z]*\n([\s\S]*?)\n```$');
    final fm = fence.firstMatch(s);
    if (fm != null) s = fm.group(1)!.trim();
    // «Мына оңдолгон текст:» сыяктуу баш сөз
    final lines = s.split('\n');
    if (lines.length > 2) {
      final first = lines.first.trim().toLowerCase();
      if (first.endsWith(':') &&
          (first.contains('текст') ||
              first.contains('оңдол') ||
              first.contains('мына'))) {
        s = lines.skip(1).join('\n').trim();
      }
    }
    return s;
  }

  /// AI жообу ишенимдүүбү: көлөмү жана таблица саптары сакталганбы.
  static bool plausible(String before, String after) {
    if (after.trim().isEmpty) return false;
    final ratio = after.length / before.length.clamp(1, 1 << 30);
    if (ratio < 0.85 || ratio > 1.2) return false;
    int rows(String t) =>
        t.split('\n').where((l) => l.trimLeft().startsWith('|')).length;
    if (rows(before) != rows(after)) return false;
    return true;
  }
}

/// Грамматиканы текшерүүнүн жыйынтыгы.
class GrammarReport {
  final String text;

  /// Жергиликтүү эрежелер менен оңдолгон жерлер.
  final int autoFixes;

  /// AI редактор канча жолу текстти карап чыкты.
  final int aiRounds;

  /// Акырында калган шектүү жерлер (көбүнчө туура болот).
  final List<String> remaining;
  const GrammarReport(this.text, this.autoFixes, this.aiRounds, this.remaining);
}
